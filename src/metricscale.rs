macro_rules! scale_mul {
    ($lhs:ty, $rhs:ty => $out:ty) => {
        impl ScaleMul<$rhs> for $lhs { type Output = $out; }
    };
}

macro_rules! scale_div {
    ($lhs:ty, $rhs:ty => $out:ty) => {
        impl ScaleDiv<$rhs> for $lhs { type Output = $out; }
    };
}

